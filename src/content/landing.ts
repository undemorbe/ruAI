export function answerFor(q: string): string {
  const hit = askExamples.find((e) => e.q.toLowerCase() === q.trim().toLowerCase())
  if (hit) return hit.a
  const t = q.trim() || 'ваш вопрос'
  return `Хороший запрос: «${t}». Полный ответ займёт пару секунд — откройте чат, и ChatGPT распишет его по шагам, с примерами и на русском.`
}

